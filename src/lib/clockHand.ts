// Стрелки часиков сроков идут в ногу. Отдельно от компонента, чтобы правило
// проверялось тестами без окна.
//
// Анимация стрелки начинается, когда стрелка появляется. Без общей фазы каждая
// новая стрелка стартовала бы с двенадцати: часики, пересозданные после «не
// удалось скопировать», и код, пришедший с обновлением данных, шли бы не в ногу
// с соседними. Поэтому у каждой стрелки отрицательная задержка — доля оборота,
// которую по часам компьютера прошла бы стрелка, запущенная в полночь 1970 года.
// Тогда в любой миг все стрелки одной скорости стоят одинаково, когда бы ни
// появились. Таймеров нет: стрелку крутят стили.

/**
 * Оборот стрелки, мс: `--move-clock` и `--move-clock-hot` в стилях при
 * включённой анимации: четыре прыжка по ≈1.2 с и по ≈0.7 с. Стили остаются
 * главными — тест сверяет эти числа с ними.
 */
export const CLOCK_TURN_MS = 4_800.6;
export const CLOCK_TURN_HOT_MS = 2_800.8;

/**
 * Задержка анимации стрелки, запущенной в миг `startMs` (часы компьютера):
 * минус доля оборота, пройденная с начала отсчёта. Горячая стрелка — со своим
 * оборотом. Записана долей переменной оборота, а не временем: при выключенном
 * тумблере «Анимация» --move — 0s, и задержка тоже 0s.
 */
export function clockHandDelay(startMs: number, hot: boolean): string {
  const turn = hot ? CLOCK_TURN_HOT_MS : CLOCK_TURN_MS;
  const phase = (startMs % turn) / turn;
  return `calc(var(${hot ? "--move-clock-hot" : "--move-clock"}) * ${(-phase).toFixed(4)})`;
}
