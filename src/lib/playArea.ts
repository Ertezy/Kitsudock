// Когда подпись и кнопка PLAY ждут фон своей игры. Отдельно от компонента,
// чтобы правило проверялось тестами без окна.
//
// С анимацией они поднимаются вслед за фоном, а не раньше него: большая
// картинка может грузиться дольше, чем длится их появление. Но главное
// действие лаунчера надолго не прячется: ожидание короче самого перетекания
// фона, а без анимации его нет вовсе — подниматься вслед не за чем, и подпись
// с кнопкой стоят на месте сразу.

/** Дольше этого подпись и кнопка фон не ждут — меньше сценической скорости
 *  (`--move-scene`, ≈0.6 с), за которую фон перетекает. */
export const ART_WAIT_MS = 500;

/**
 * Прятать ли подпись и кнопку. `motion` — включена ли анимация, `artShown` —
 * начал ли проявляться фон их игры, `waitedEnough` — вышло ли `ART_WAIT_MS`.
 */
export function playAreaWaiting(motion: boolean, artShown: boolean, waitedEnough: boolean): boolean {
  return motion && !artShown && !waitedEnough;
}
