// «Запускаю…» на кнопке PLAY после удачного запуска. Отдельно от компонента,
// чтобы правило проверялось тестами без окна.
//
// Окно после «Играть» теперь остаётся открытым (спека полировки, §8.1), и
// удачный запуск отвечает за одну поездку к Rust: надпись «Запускаю…»
// мелькнула бы быстрее собственной смены. А игра из exe показывает своё окно
// через 5–15 с — человек решил бы, что ничего не произошло, нажал бы ещё раз и
// запустил игру дважды. Поэтому после удачного запуска кнопка остаётся занятой,
// пока окно не станет неактивным — фокус забрала игра или её лаунчер, или окно
// спряталось в трей (`lib/windowActive.ts`), — но не дольше потолка.
// С анимацией и без неё одинаково: надпись — не движение.

/**
 * Потолок удержания. Игра может так и не забрать фокус (лаунчер уже открыт и
 * свёрнут, игра стартует в фоне) — кнопка не должна застрять занятой. 8 с
 * покрывают окно большинства игр из exe; если игра медленнее, кнопка
 * освобождается раньше, чем окно игры появится, но надпись к этому времени
 * уже успела сказать, что запуск идёт.
 */
export const LAUNCH_HOLD_MS = 8_000;

/** Что случилось с запуском или с окном. */
export type LaunchEvent =
  /** Rust ответил на запуск; `windowActive` — активно ли окно в этот миг. */
  | { kind: "answered"; ok: boolean; windowActive: boolean }
  /** Окно стало активным или неактивным. */
  | { kind: "windowActive"; active: boolean }
  /** Вышел `LAUNCH_HOLD_MS` с удачного ответа. */
  | { kind: "capped" };

/**
 * Держит ли кнопка «Запускаю…» после ответа на запуск — шаг для `useReducer`.
 * Неудача не держит: ошибка видна сразу, как раньше. Окно, неактивное уже к
 * ответу (игра забрала фокус, пока шёл запрос, или окно ушло в трей), — тоже:
 * запуск и так виден. Вернувшееся окно удержание не возобновляет.
 */
export function launchHeld(held: boolean, event: LaunchEvent): boolean {
  switch (event.kind) {
    case "answered":
      return event.ok && event.windowActive;
    case "windowActive":
      return held && event.active;
    case "capped":
      return false;
  }
}
