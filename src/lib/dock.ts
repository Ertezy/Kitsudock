// Увеличение иконок дока под курсором. Отдельно от компонента, чтобы расчёт
// проверялся тестами без окна.
//
// Иконка растёт растяжением (`transform: scale`), а не шириной и высотой:
// спека полировки (§2) разрешает анимировать только `transform` и `opacity`.
// Растяжение не трогает раскладку, поэтому соседей раздвигает не она, а сдвиг,
// посчитанный здесь: каждая иконка уходит вбок ровно настолько, насколько
// выросли иконки перед ней, — так же, как раньше раздвигала раскладка. Ряд по
// центру экрана растёт в обе стороны поровну, и здесь так же.
//
// Сдвиг считается в долях полного прироста одной иконки: сколько это в точках,
// решают стили (`--dock-grow`), рядом с размером и кратностью увеличения.

/** Близость курсора к каждой иконке, от 0 (дальше `reach`) до 1 (курсор над центром). */
export function nearness(centres: number[], x: number, reach: number): number[] {
  return centres.map((c) => Math.max(0, 1 - Math.abs(x - c) / reach));
}

/**
 * Сдвиг каждой иконки вдоль ряда, в долях полного прироста одной иконки.
 * Иконка растёт от своего центра, поэтому её соседи расходятся на половины
 * приростов обеих: зазор между ними остаётся прежним, и наложиться им негде.
 */
export function shifts(near: number[]): number[] {
  const total = near.reduce((sum, n) => sum + n, 0);
  let before = 0;
  return near.map((n) => {
    const shift = before + n / 2 - total / 2;
    before += n;
    return shift;
  });
}

/**
 * Во сколько раз растянуть стеклянную подложку по ширине, чтобы она осталась
 * вокруг раздвинувшегося ряда. `grow` — полный прирост одной иконки в точках,
 * `width` — ширина подложки в покое.
 */
export function glassScale(near: number[], grow: number, width: number): number {
  if (!(width > 0)) return 1;
  const total = near.reduce((sum, n) => sum + n, 0);
  return 1 + (grow * total) / width;
}
