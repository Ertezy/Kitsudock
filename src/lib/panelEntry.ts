// Когда разделы боковой панели проигрывают вход и когда вместо них стоят
// заглушки. Отдельно от компонента, чтобы правила проверялись тестами без окна.
//
// Вход — короткая лесенка: разделы по очереди поднимаются и проявляются. Он
// играет, когда панель появляется (запуск, возврат из настроек), и когда данные
// пришли впервые — тогда на месте заглушек встают карточки. Обновление данных и
// смена игры в доке лесенку не повторяют: панель, которая заново собирается от
// каждого обновления, мельтешила бы, а раздел, появившийся при смене игры,
// встаёт сразу, как и содержимое соседних.

/**
 * Какой вход идёт. `mount` — панель только появилась: разделы (или заглушки)
 * ждут, пока она почти выедет. `data` — данные пришли позже: разделы встают
 * сразу, на место только что пропавших заглушек, без пустой паузы между ними.
 */
export type EntryKind = "mount" | "data";

export interface PanelEntry {
  /** Данные панели уже пришли. */
  loaded: boolean;
  /** Номер входа. Растёт с каждым новым, чтобы конец прежнего не оборвал новый. */
  run: number;
  /** Какой вход идёт; `null` — никакого. */
  kind: EntryKind | null;
}

/** Панель появилась: вход начинается сам, есть данные или нет. */
export function panelMounted(loaded: boolean): PanelEntry {
  return { loaded, run: 1, kind: "mount" };
}

/**
 * Данные панели есть или нет. Пришли впервые — новый вход, и разделы встают
 * сразу, даже если панель ещё выезжает: заглушки к этому мигу могли уже
 * проступить, и выжидание оставило бы на их месте пустоту. Обновление уже
 * пришедших данных возвращает тот же объект: ничего не перезапускается.
 */
export function hubChanged(entry: PanelEntry, loaded: boolean): PanelEntry {
  if (loaded === entry.loaded) return entry;
  if (!loaded) return { ...entry, loaded };
  return { loaded, run: entry.run + 1, kind: "data" };
}

/** Доиграли анимации входа с номером `run`. Конец прежнего входа новый не снимает. */
export function entryEnded(entry: PanelEntry, run: number): PanelEntry {
  return entry.kind !== null && entry.run === run ? { ...entry, kind: null } : entry;
}

/** Имена кадров входа в стилях: по их концу вход считается сыгранным. */
export const ENTRY_ANIMATIONS: readonly string[] = ["panel-rise", "panel-fade"];

/** Анимация с этим именем кадров — часть входа. */
export function isEntryAnimation(name: string): boolean {
  return ENTRY_ANIMATIONS.includes(name);
}

/**
 * Показывать ли заглушки разделов: данных ещё нет, а у выбранной игры они
 * вообще бывают. Игра без привязки к данным (`contentId` пуст) и после их
 * прихода останется без кодов, баннеров и видео — заглушки обещали бы то,
 * чего не будет.
 */
export function skeletonShown(loaded: boolean, contentId: string | null): boolean {
  return !loaded && contentId !== null;
}
